  'use strict';
  /**
   * db.js - SQLite setup and every query the hub needs.
   *
   * All SQL lives here so the rest of the code never builds queries by hand.
   * better-sqlite3 is synchronous, which keeps the code simple: no callbacks,
   * and Node's single thread means two requests can never interleave inside
   * one of these functions.
   *
   * Tables: devices, users, signals, orders, order_receipts, positions.
   *   - order_receipts is an extra table: an order sent to "ALL" is delivered
   *     to many phones, so we track DELIVERED/READ per unit.
   */
  require('dotenv').config();
  const fs = require('fs');
  const path = require('path');
  const Database = require('better-sqlite3');

  const DB_PATH = process.env.DB_PATH || './data/signal-hub.db';
  fs.mkdirSync(path.dirname(path.resolve(DB_PATH)), { recursive: true });

  const db = new Database(DB_PATH);
  db.pragma('journal_mode = WAL'); // readers don't block the writer
  db.pragma('foreign_keys = ON');

  // ---------------------------------------------------------------------------
  // Schema
  // ---------------------------------------------------------------------------
  db.exec(`
  CREATE TABLE IF NOT EXISTS devices (
    id              TEXT PRIMARY KEY,
    callsign        TEXT NOT NULL,
    device_key_hash TEXT NOT NULL,              -- "salt:sha256(salt+key)", never the key itself
    team_code       TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','revoked')),
    last_seen       INTEGER,                    -- epoch ms of the last signal
    battery         INTEGER,                    -- 0-100
    created_at      INTEGER NOT NULL
  );
  -- A callsign can only be used by one ACTIVE device (a revoked one frees it up).
  CREATE UNIQUE INDEX IF NOT EXISTS idx_devices_callsign_active
    ON devices (callsign) WHERE status = 'active';

  CREATE TABLE IF NOT EXISTS users (            -- dashboard logins
    username      TEXT PRIMARY KEY,
    password_hash TEXT NOT NULL,                -- bcrypt
    created_at    INTEGER NOT NULL
  );

  CREATE TABLE IF NOT EXISTS signals (
    id          TEXT PRIMARY KEY,               -- generated by the phone => idempotent inserts
    unit        TEXT NOT NULL,
    type        TEXT NOT NULL,
    priority    TEXT NOT NULL,                  -- critical | high | normal
    sub_type    TEXT,                           -- e.g. "MOVING" (the field app sends this)
    lat         REAL NOT NULL,
    lon         REAL NOT NULL,
    note        TEXT,
    photo_thumb TEXT,                           -- optional small base64 image (<= 100 KB)
    timestamp   INTEGER NOT NULL,               -- epoch ms, set by the phone
    status      TEXT NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED','ACKNOWLEDGED')),
    received_at INTEGER NOT NULL                -- epoch ms, set by the server
  );
  CREATE INDEX IF NOT EXISTS idx_signals_unit_time ON signals (unit, timestamp);
  CREATE INDEX IF NOT EXISTS idx_signals_time      ON signals (timestamp);

  CREATE TABLE IF NOT EXISTS orders (
    id          TEXT PRIMARY KEY,
    target_unit TEXT NOT NULL,                  -- a callsign or "ALL"
    title       TEXT NOT NULL,
    text        TEXT NOT NULL,
    priority    TEXT NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('NORMAL','URGENT')),
    sender      TEXT NOT NULL DEFAULT 'COMMAND HQ',
    status      TEXT NOT NULL DEFAULT 'SENT' CHECK (status IN ('SENT','DELIVERED','READ')),
    created_at  INTEGER NOT NULL
  );

  CREATE TABLE IF NOT EXISTS order_receipts (   -- per-unit delivery state of an order
    order_id   TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    unit       TEXT NOT NULL,
    status     TEXT NOT NULL CHECK (status IN ('DELIVERED','READ')),
    updated_at INTEGER NOT NULL,
    PRIMARY KEY (order_id, unit)
  );

  CREATE TABLE IF NOT EXISTS positions (        -- GPS trail points
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    unit      TEXT NOT NULL,
    lat       REAL NOT NULL,
    lon       REAL NOT NULL,
    timestamp INTEGER NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_positions_unit_time ON positions (unit, timestamp);
  `);

  // ---------------------------------------------------------------------------
  // Prepared statements (compiled once, reused for every call)
  // ---------------------------------------------------------------------------
  const UNIT_SELECT = `
    SELECT d.id AS device_id, d.callsign, d.team_code, d.last_seen, d.battery,
          p.lat AS pos_lat, p.lon AS pos_lon, p.timestamp AS pos_time,
          (SELECT COUNT(*) FROM signals s
              WHERE s.unit = d.callsign AND s.type = 'SOS' AND s.status = 'RECEIVED') AS open_sos
    FROM devices d
    LEFT JOIN positions p ON p.id = (
      SELECT id FROM positions WHERE unit = d.callsign ORDER BY timestamp DESC, id DESC LIMIT 1)
    WHERE d.status = 'active'`;

  const st = {
    insertDevice: db.prepare(`INSERT INTO devices (id, callsign, device_key_hash, team_code, status, created_at)
                              VALUES (@id, @callsign, @keyHash, @teamCode, 'active', @createdAt)`),
    getDevice: db.prepare('SELECT * FROM devices WHERE id = ?'),
    getActiveByCallsign: db.prepare(`SELECT * FROM devices WHERE callsign = ? AND status = 'active'`),
    listDevices: db.prepare(`SELECT id, callsign, team_code, status, last_seen, battery, created_at
                            FROM devices ORDER BY callsign, created_at`),
    revokeDevice: db.prepare(`UPDATE devices SET status = 'revoked' WHERE id = ? AND status = 'active'`),
    touchDevice: db.prepare(`UPDATE devices SET last_seen = @lastSeen, battery = COALESCE(@battery, battery)
                            WHERE id = @id`),

    getUser: db.prepare('SELECT * FROM users WHERE username = ?'),
    upsertUser: db.prepare(`INSERT INTO users (username, password_hash, created_at) VALUES (@username, @hash, @now)
                            ON CONFLICT(username) DO UPDATE SET password_hash = excluded.password_hash`),

    insertSignal: db.prepare(`INSERT OR IGNORE INTO signals
        (id, unit, type, priority, sub_type, lat, lon, note, photo_thumb, timestamp, status, received_at)
        VALUES (@id, @unit, @type, @priority, @subType, @lat, @lon, @note, @photoThumb, @timestamp, 'RECEIVED', @receivedAt)`),
    getSignal: db.prepare('SELECT * FROM signals WHERE id = ?'),
    ackSignal: db.prepare(`UPDATE signals SET status = 'ACKNOWLEDGED' WHERE id = ? AND status = 'RECEIVED'`),
    recentAcked: db.prepare(`SELECT id FROM signals WHERE unit = ? AND status = 'ACKNOWLEDGED'
                            ORDER BY received_at DESC LIMIT ?`),
    exportSignals: db.prepare(`SELECT id, unit, type, sub_type, priority, lat, lon, note, timestamp, status, received_at
                              FROM signals ORDER BY timestamp ASC`),

    insertPosition: db.prepare('INSERT INTO positions (unit, lat, lon, timestamp) VALUES (@unit, @lat, @lon, @timestamp)'),
    trail: db.prepare(`SELECT unit, lat, lon, timestamp FROM positions
                      WHERE unit = @unit AND timestamp >= @from AND timestamp <= @to
                      ORDER BY timestamp DESC LIMIT @limit`),

    units: db.prepare(`${UNIT_SELECT} ORDER BY d.callsign`),
    unitOne: db.prepare(`${UNIT_SELECT} AND d.callsign = ?`),

    insertOrder: db.prepare(`INSERT INTO orders (id, target_unit, title, text, priority, sender, status, created_at)
                            VALUES (@id, @targetUnit, @title, @text, @priority, @sender, 'SENT', @createdAt)`),
    getOrder: db.prepare('SELECT * FROM orders WHERE id = ?'),
    listOrders: db.prepare('SELECT * FROM orders ORDER BY created_at DESC LIMIT ?'),
    listOrdersForUnit: db.prepare(`SELECT * FROM orders WHERE target_unit = ? OR target_unit = 'ALL'
                                  ORDER BY created_at DESC LIMIT ?`),
    // Orders for a unit that it has no receipt for yet (i.e. not DELIVERED / READ).
    pendingOrders: db.prepare(`SELECT o.* FROM orders o
        WHERE (o.target_unit = @unit OR o.target_unit = 'ALL')
          AND o.created_at >= @since
          AND NOT EXISTS (SELECT 1 FROM order_receipts r WHERE r.order_id = o.id AND r.unit = @unit)
        ORDER BY o.created_at ASC`),
    // The field app echoes the last 6 chars of an order id inside its ACK signal note.
    orderBySuffix: db.prepare(`SELECT * FROM orders
        WHERE (target_unit = @unit OR target_unit = 'ALL') AND lower(substr(id, -6)) = lower(@suffix)
        ORDER BY created_at DESC LIMIT 1`),
    getReceipt: db.prepare('SELECT * FROM order_receipts WHERE order_id = ? AND unit = ?'),
    upsertReceipt: db.prepare(`INSERT INTO order_receipts (order_id, unit, status, updated_at)
        VALUES (@orderId, @unit, @status, @now)
        ON CONFLICT(order_id, unit) DO UPDATE SET status = excluded.status, updated_at = excluded.updated_at`),
    receiptStatuses: db.prepare('SELECT status FROM order_receipts WHERE order_id = ?'),
    setOrderStatus: db.prepare('UPDATE orders SET status = ? WHERE id = ?'),
  };

  // ---------------------------------------------------------------------------
  // Helpers
  // ---------------------------------------------------------------------------
  const transaction = (fn) => db.transaction(fn)(); // run fn atomically
  const ORDER_RANK = { SENT: 0, DELIVERED: 1, READ: 2 };
  const PENDING_WINDOW_MS = 24 * 60 * 60 * 1000;     // "ALL" orders older than this are not re-sent

  /** Signal history with optional filters. Newest first. */
  function querySignals({ unit, type, from, to, limit = 500, offset = 0, photos = false }) {
    const where = [];
    const params = [];
    if (unit) { where.push('unit = ?'); params.push(String(unit).toUpperCase()); }
    if (type) { where.push('type = ?'); params.push(String(type).toUpperCase()); }
    if (from != null) { where.push('timestamp >= ?'); params.push(from); }
    if (to != null) { where.push('timestamp <= ?'); params.push(to); }
    const sql = `SELECT id, unit, type, priority, sub_type, lat, lon, note,
                        ${photos ? 'photo_thumb,' : ''} timestamp, status, received_at
                FROM signals ${where.length ? 'WHERE ' + where.join(' AND ') : ''}
                ORDER BY timestamp DESC LIMIT ? OFFSET ?`;
    return db.prepare(sql).all(...params, limit, offset);
  }

  /**
   * Record that `unit` reached `status` for an order. Never downgrades
   * (READ stays READ). Also bumps the order's overall status to the highest
   * status reached by any recipient. Returns { changed, orderStatus }.
   */
  function setReceipt(orderId, unit, status) {
    const current = st.getReceipt.get(orderId, unit);
    if (current && ORDER_RANK[current.status] >= ORDER_RANK[status]) {
      return { changed: false };
    }
    st.upsertReceipt.run({ orderId, unit, status, now: Date.now() });
    const order = st.getOrder.get(orderId);
    const best = st.receiptStatuses.all(orderId)
      .reduce((acc, r) => (ORDER_RANK[r.status] > ORDER_RANK[acc] ? r.status : acc), order.status);
    if (best !== order.status) st.setOrderStatus.run(best, orderId);
    return { changed: true, orderStatus: best };
  }

  /** Delete everything (used by `seed.js --reset`). */
  function wipeAll() {
    transaction(() => {
      for (const t of ['order_receipts', 'orders', 'positions', 'signals', 'devices', 'users']) {
        db.prepare(`DELETE FROM ${t}`).run();
      }
    });
  }

  module.exports = {
    db,
    transaction,
    wipeAll,
    querySignals,
    setReceipt,
    // devices
    insertDevice: (d) => st.insertDevice.run(d),
    getDevice: (id) => st.getDevice.get(id),
    getActiveDeviceByCallsign: (cs) => st.getActiveByCallsign.get(cs),
    listDevices: () => st.listDevices.all(),
    revokeDevice: (id) => st.revokeDevice.run(id).changes === 1,
    touchDevice: (id, lastSeen, battery) => st.touchDevice.run({ id, lastSeen, battery: battery ?? null }),
    // users
    getUser: (u) => st.getUser.get(u),
    upsertUser: (username, hash) => st.upsertUser.run({ username, hash, now: Date.now() }),
    // signals + positions
    insertSignal: (s) => st.insertSignal.run(s),
    getSignal: (id) => st.getSignal.get(id),
    ackSignal: (id) => st.ackSignal.run(id).changes === 1,
    recentAcknowledged: (unit, limit = 50) => st.recentAcked.all(unit, limit),
    iterateSignalsForExport: () => st.exportSignals.iterate(),
    insertPosition: (p) => st.insertPosition.run(p),
    getTrail: (unit, from, to, limit) => st.trail.all({ unit, from, to, limit }),
    // units
    listUnits: () => st.units.all(),
    getUnit: (callsign) => st.unitOne.get(callsign),
    // orders
    insertOrder: (o) => st.insertOrder.run(o),
    getOrder: (id) => st.getOrder.get(id),
    listOrders: (limit = 200) => st.listOrders.all(limit),
    listOrdersForUnit: (unit, limit = 200) => st.listOrdersForUnit.all(unit, limit),
    pendingOrders: (unit) => st.pendingOrders.all({ unit, since: Date.now() - PENDING_WINDOW_MS }),
    findOrderBySuffix: (unit, suffix) => st.orderBySuffix.get({ unit, suffix }),
  };
